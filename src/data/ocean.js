export function oceanTopic(question) {
  if (/특수선|잠수함|수상함|함정/.test(question)) return 'naval';
  if (/해양설비|해양 사업|FLNG|FPSO|플랜트/.test(question)) return 'offshore';
  return 'lng';
}

export function oceanAnswer(question, audience) {
  const index = OCEAN_QUESTIONS[audience]?.indexOf(question) ?? -1;
  if (index < 0) return {
    summary: '현재 도감에서는 이 질문에 맞는 근거를 충분히 확인하지 못했어요. 아래 추천 질문을 선택하거나 공식 자료에서 선박·해양설비의 역할을 살펴봐 주세요.',
    mode: 'demo', insufficient: true, sources: [],
  };
  const sources = [...new Map(FACILITIES.filter(f => TOPICS[audience][index].includes(f.id)).flatMap(f => f.sources).map(s => [s.id, s])).values()];
  return { summary: ANSWERS[audience][index], mode: 'demo', insufficient: false, sources };
}
